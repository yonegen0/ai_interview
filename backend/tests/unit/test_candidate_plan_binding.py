@pytest.mark.parametrize(
    "mutation",
    [
        "wrong-operation",
        "old-schema",
        "bool-schema",
        "old-kind",
        "missing",
        "extra",
        "bad-type",
        "missing-evidence",
        "extra-evidence",
        "bad-evidence-hash",
        "empty-binary",
        "same-approval",
        "missing-approval",
    ],
)
def test_partial_plan_old_schema_or_approval_reuse_rejected(sample, mutation):
    m, plan, expected, binary = sample
    args = {
        "apply_operation": "maintenance-apply",
        "plan_binary": binary,
        "plan_approval_id": "1" * 40,
        "apply_approval_id": "2" * 40,
    }
    if mutation == "wrong-operation":
        plan["operation"] = "recovery-plan"
    elif mutation == "old-schema":
        plan["schema_version"] = 2
    elif mutation == "bool-schema":
        plan["schema_version"] = True
    elif mutation == "old-kind":
        plan["kind"] = "historical"
    elif mutation == "missing":
        del plan["git_tree_sha"]
    elif mutation == "extra":
        plan["authenticated"] = True
    elif mutation == "bad-type":
        plan["terraform_sha256"] = False
    elif mutation == "missing-evidence":
        del plan["generation_evidence"]
    elif mutation == "extra-evidence":
        plan["generation_evidence"]["signature_verified"] = True
    elif mutation == "bad-evidence-hash":
        plan["generation_evidence"]["evidence_sha256"] = "invalid"
    elif mutation == "empty-binary":
        args["plan_binary"] = b""
    elif mutation == "same-approval":
        args["apply_approval_id"] = args["plan_approval_id"]
    elif mutation == "missing-approval":
        args["apply_approval_id"] = None
    with pytest.raises(ValueError):
        m.validate_plan_binding(plan, expected, **args)


def test_recovery_and_maintenance_plan_generation_are_not_interchangeable(sample):
    sample[1]["operation"] = "recovery-plan"
    assert run(sample, operation="recovery-apply")["authorized"] is False
    with pytest.raises(ValueError):
        run(sample, operation="maintenance-apply")


def test_no_aws_terraform_subprocess_or_network_calls(sample, monkeypatch):
    import socket
    import subprocess

    def forbidden(*args, **kwargs):
        raise AssertionError("Terraform/network not permitted")

    monkeypatch.setattr(subprocess, "run", forbidden)
    monkeypatch.setattr(socket, "create_connection", forbidden)
    assert run(sample)["authorized"] is False


