def test_tracked_fifo_is_rejected_without_waiting_for_a_writer(synthetic_git_checkout):  # noqa: F811
    root, commit = synthetic_git_checkout
    m = tool("candidate_artifact_snapshot")
    path = root / "terraform/bootstrap/main.tf"
    path.unlink()
    os.mkfifo(path)
    script = """
import sys
from pathlib import Path
sys.path.insert(0, sys.argv[1])
import candidate_artifact_snapshot as snapshot
try:
    snapshot.capture_source(Path(sys.argv[2]), sys.argv[3])
except ValueError as error:
    assert str(error) == "CandidateGitNonregularFile", str(error)
else:
    raise AssertionError("FIFO accepted")
"""
    subprocess.run(
        [sys.executable, "-c", script, str(m.Path(m.__file__).parent), str(root), commit],
        check=True,
        capture_output=True,
        timeout=5,
    )


def test_git_commit_tree_and_snapshot_bytes_remain_distinct_from_execution(synthetic_git_checkout):  # noqa: F811
    root, commit = synthetic_git_checkout
    m = tool("candidate_artifact_snapshot")
    snapshot = m.capture_source(root, commit)
    assert snapshot.source_sha == commit
    assert len(snapshot.git_tree_sha) == 40
    assert snapshot.authorized is snapshot.git_origin_authenticated is False
    assert snapshot.immutable_execution_snapshot_verified is False
    assert type(snapshot.files) is tuple
    assert all(type(raw) is bytes for _, raw in snapshot.files)
    original = snapshot.files
    (root / "terraform/bootstrap/main.tf").write_bytes(b"changed")
    with pytest.raises(ValueError, match="BlobMismatch"):
        m.assert_source_unchanged(snapshot)
    assert snapshot.files == original


def test_checkout_swap_with_identical_bytes_is_detected(synthetic_git_checkout, tmp_path):  # noqa: F811
    root, commit = synthetic_git_checkout
    m = tool("candidate_artifact_snapshot")
    snapshot = m.capture_source(root, commit)
    alternate = tmp_path / "alternate"
    shutil.copytree(root, alternate)
    root.rename(tmp_path / "preserved")
    alternate.rename(root)
    with pytest.raises(ValueError, match="ReplacedHOLD"):
        m.assert_source_unchanged(snapshot)


def test_source_change_during_capture_is_rejected(synthetic_git_checkout, monkeypatch):  # noqa: F811
    root, commit = synthetic_git_checkout
    m = tool("candidate_artifact_snapshot")
    original = m.local.verified_git_source_inventory
    calls = 0

    def race(*args):
        nonlocal calls
        observed = original(*args)
        calls += 1
        if calls == 1:
            (root / "terraform/bootstrap/injected.tf").write_bytes(b"terraform {}")
        return observed

    monkeypatch.setattr(m.local, "verified_git_source_inventory", race)
    with pytest.raises(ValueError, match="UntrackedFile"):
        m.capture_source(root, commit)


@pytest.mark.parametrize("mutation", ["empty", "digest", "oversize", "symlink"])
def test_plan_snapshot_rejects_mutation_and_nonregular_target(tmp_path, mutation):
    m = tool("candidate_artifact_snapshot")
    path = tmp_path / "saved-plan"
    raw = b"synthetic plan not generated by Terraform"
    path.write_bytes(raw)
    digest = hashlib.sha256(raw).hexdigest()
    assert m.read_plan_snapshot(path, digest) == raw
    if mutation == "empty":
        path.write_bytes(b"")
    elif mutation == "digest":
        path.write_bytes(b"changed")
    elif mutation == "oversize":
        with pytest.raises(ValueError):
            m.read_plan_snapshot(path, digest, max_bytes=1)
        return
    else:
        link = tmp_path / "link"
        link.symlink_to(path)
        path = link
    with pytest.raises(ValueError):
        m.read_plan_snapshot(path, digest)


def test_plan_byte_snapshot_survives_later_leaf_substitution_but_cannot_authorize(tmp_path):
    m = tool("candidate_artifact_snapshot")
    path = tmp_path / "plan"
    path.write_bytes(b"original")
    digest = hashlib.sha256(b"original").hexdigest()
    snapshot = m.read_plan_snapshot(path, digest)
    path.write_bytes(b"substituted")
    assert snapshot == b"original"
    with pytest.raises(ValueError):
        m.read_plan_snapshot(path, digest)
